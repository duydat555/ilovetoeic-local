import { QuestionEvidence } from '../types';

const decodeBasicEntities = (value: string) =>
  value
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&nbsp;/gi, ' ');

const cleanDownloadedText = (value: string) =>
  decodeBasicEntities(
    value
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/p\s*>/gi, '\n')
      .replace(/<[^>]+>/g, '')
      .replace(/\*\*/g, '')
      .replace(/\$\\approx\$/g, '≈')
      .replace(/\r\n?/g, '\n'),
  )
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

/**
 * Evidence is not generated by the client. It is parsed only when the
 * downloaded explanation_vi field explicitly contains a "Dẫn chứng" marker.
 */
export const parseQuestionEvidence = (source?: string | null): QuestionEvidence | undefined => {
  if (!source) return undefined;

  const normalized = cleanDownloadedText(source);
  const paraphraseMarker = /(?:^|[\n\r]+|[ \t]+)-?\s*Paraphrase\s*:/i.exec(normalized);
  const evidenceBlock = paraphraseMarker
    ? normalized.slice(0, paraphraseMarker.index)
    : normalized;
  const paraphrase = paraphraseMarker
    ? normalized.slice(paraphraseMarker.index + paraphraseMarker[0].length).trim()
    : '';

  const markerPattern = /Dẫn chứng(?:\s*(\d+))?\s*:/gi;
  const matches = [...evidenceBlock.matchAll(markerPattern)];
  if (matches.length === 0) return undefined;

  const citations = matches
    .map((match, index) => {
      const start = (match.index ?? 0) + match[0].length;
      const end = matches[index + 1]?.index ?? evidenceBlock.length;
      const text = evidenceBlock
        .slice(start, end)
        .trim()
        .replace(/^\s*-\s*/, '')
        .replace(/\s*-\s*$/, '')
        .trim();
      return {
        label: match[1] ? `Dẫn chứng ${match[1]}` : 'Dẫn chứng',
        text,
      };
    })
    .filter((citation) => citation.text.length > 0);

  if (citations.length === 0) return undefined;
  return {
    citations,
    paraphrase: paraphrase || undefined,
  };
};
